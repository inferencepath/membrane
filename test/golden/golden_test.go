// Package golden provides per-family wire-format golden tests.
//
// For every Provider family in the factory registry it drives the adapter's
// non-streaming Complete() against a capturing fake upstream and asserts:
//
//   - the outbound wire REQUEST body matches a recorded, identity-free fixture
//     under test/golden/<family>/request.json; and
//   - the recorded upstream RESPONSE maps to a schema-identical CanonicalResponse
//     recorded under test/golden/<family>/response.json.
//
// The family set is derived from factory.Families(), so a new family without a
// golden fixture fails CI. Fixtures are regenerated by running the
// suite with UPDATE_GOLDEN=1. Golden files never contain credentials or Caller
// identity: only the adapter's BODY (not its signed headers) is recorded.
package golden

import (
	"context"
	"encoding/json"
	"io"
	"net/http"
	"net/http/httptest"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"sync"
	"testing"

	"github.com/inferencepath/membrane/internal/exterior/providers"
	"github.com/inferencepath/membrane/internal/exterior/providers/anthropic"
	"github.com/inferencepath/membrane/internal/exterior/providers/azureopenai"
	"github.com/inferencepath/membrane/internal/exterior/providers/bedrock"
	"github.com/inferencepath/membrane/internal/exterior/providers/factory"
	"github.com/inferencepath/membrane/internal/exterior/providers/gemini"
	"github.com/inferencepath/membrane/internal/exterior/providers/openai"
	"github.com/inferencepath/membrane/internal/types"
)

// assertGolden compares got to the fixture at path. With UPDATE_GOLDEN set (or
// when the fixture does not yet exist) it (re)writes the fixture instead.
func assertGolden(t *testing.T, path string, got []byte) {
	t.Helper()
	got = append(got, '\n')
	_, statErr := os.Stat(path)
	if os.Getenv("UPDATE_GOLDEN") != "" || os.IsNotExist(statErr) {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatalf("mkdir golden: %v", err)
		}
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatalf("write golden: %v", err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read golden %s: %v", path, err)
	}
	if string(want) != string(got) {
		t.Fatalf("golden mismatch for %s\n--- want ---\n%s\n--- got ---\n%s", path, want, got)
	}
}

// responseFor returns the canned upstream reply (and content type) each family's
// Complete() consumes, in that family's native wire schema.
func responseFor(family string) (body, contentType string) {
	switch family {
	case "anthropic":
		// Anthropic Messages schema.
		return `{"model":"claude-golden","stop_reason":"end_turn",` +
			`"content":[{"type":"text","text":"hello from golden"}],` +
			`"usage":{"input_tokens":3,"output_tokens":5}}`, "application/json"
	case "bedrock":
		// Bedrock Converse schema (model-agnostic).
		return `{"output":{"message":{"role":"assistant",` +
			`"content":[{"text":"hello from golden"}]}},"stopReason":"end_turn",` +
			`"usage":{"inputTokens":3,"outputTokens":5,"totalTokens":8}}`, "application/json"
	case "gemini":
		// Gemini generateContent schema.
		return `{"candidates":[{"content":{"parts":[{"text":"hello from golden"}]},` +
			`"finishReason":"STOP"}],` +
			`"usageMetadata":{"promptTokenCount":3,"candidatesTokenCount":5,"totalTokenCount":8}}`, "application/json"
	default: // openai, local, azure-openai (OpenAI-compatible schema)
		return `{"model":"gpt-golden","choices":[{"message":{"role":"assistant",` +
			`"content":"hello from golden"},"finish_reason":"stop"}],` +
			`"usage":{"prompt_tokens":3,"completion_tokens":5,"total_tokens":8}}`, "application/json"
	}
}

// adapterFor builds the family's adapter pointed at endpoint, plus the
// EgressIdentity its Complete() requires.
func adapterFor(t *testing.T, family, endpoint string) (providers.Provider, providers.EgressIdentity) {
	t.Helper()
	switch family {
	case "openai", "local":
		return openai.New(types.ProviderID(family), endpoint, 0), providers.EgressIdentity{Secret: "sk-golden-EGRESS"}
	case "anthropic":
		return anthropic.New(endpoint, 0), providers.EgressIdentity{Secret: "sk-ant-golden-EGRESS"}
	case "azure-openai":
		return azureopenai.New(endpoint, "deploy-golden", 0), providers.EgressIdentity{Secret: "azure-golden-EGRESS"}
	case "bedrock":
		return bedrock.New("us-east-1", endpoint, 0), providers.EgressIdentity{Secret: "AKIAGOLDEN:secretGolden"}
	case "gemini":
		return gemini.New(endpoint, 0), providers.EgressIdentity{Secret: "gemini-golden-EGRESS"}
	default:
		t.Fatalf("golden suite has no coverage for family %q (add a fixture)", family)
		return nil, providers.EgressIdentity{}
	}
}

// goldenRequest is the fixed, identity-free egress request every family maps.
func goldenRequest() providers.Request {
	return providers.Request{
		Model: "golden-model",
		Payload: map[string]any{
			"messages":    []any{map[string]any{"role": "user", "content": "hi"}},
			"temperature": 0.2,
		},
		Stream: false,
	}
}

func TestGoldenWirePerFamily(t *testing.T) {
	families := factory.Families()
	if len(families) == 0 {
		t.Fatal("factory.Families() is empty; registry enumeration broken")
	}
	for _, family := range families {
		family := family
		t.Run(family, func(t *testing.T) {
			var (
				mu       sync.Mutex
				captured []byte
			)
			respBody, ct := responseFor(family)
			srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				b, _ := io.ReadAll(r.Body)
				mu.Lock()
				captured = b
				mu.Unlock()
				w.Header().Set("Content-Type", ct)
				_, _ = io.WriteString(w, respBody)
			}))
			defer srv.Close()

			adapter, id := adapterFor(t, family, srv.URL)
			resp, err := adapter.Complete(context.Background(), goldenRequest(), id)
			if err != nil {
				t.Fatalf("Complete: %v", err)
			}

			// Outbound request body is deterministic and identity-free.
			var reqObj map[string]any
			if err := json.Unmarshal(captured, &reqObj); err != nil {
				t.Fatalf("captured request not JSON: %v (%s)", err, captured)
			}
			reqGolden, err := json.MarshalIndent(reqObj, "", "  ")
			if err != nil {
				t.Fatal(err)
			}
			assertGolden(t, filepath.Join("testdata", family, "request.json"), reqGolden)

			// Upstream reply maps to a schema-identical CanonicalResponse.
			respGolden, err := json.MarshalIndent(resp, "", "  ")
			if err != nil {
				t.Fatal(err)
			}
			assertGolden(t, filepath.Join("testdata", family, "response.json"), respGolden)
		})
	}
}

// TestGoldenCrossFamilySchema asserts every family maps its native reply to the
// SAME CanonicalResponse schema (identical field set), proving provider-neutral
// normalization regardless of upstream wire format.
func TestGoldenCrossFamilySchema(t *testing.T) {
	var wantKeys []string
	for i, family := range factory.Families() {
		respBody, ct := responseFor(family)
		srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
			w.Header().Set("Content-Type", ct)
			_, _ = io.WriteString(w, respBody)
		}))
		adapter, id := adapterFor(t, family, srv.URL)
		resp, err := adapter.Complete(context.Background(), goldenRequest(), id)
		srv.Close()
		if err != nil {
			t.Fatalf("%s Complete: %v", family, err)
		}
		b, _ := json.Marshal(resp)
		var m map[string]any
		if err := json.Unmarshal(b, &m); err != nil {
			t.Fatal(err)
		}
		keys := make([]string, 0, len(m))
		for k := range m {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		if i == 0 {
			wantKeys = keys
			continue
		}
		if strings.Join(keys, ",") != strings.Join(wantKeys, ",") {
			t.Fatalf("family %q canonical schema differs: got keys %v, want %v", family, keys, wantKeys)
		}
	}
}
